class LiveChatSession(models.Model):
    """
    Live chat between a seller and a bot-captured customer.

    Created automatically when a Customer is created from a published bot entry.
    Customer-side access is authenticated via `public_token` (non-guessable).
    """

    session_id = models.AutoField(primary_key=True)
    seller_user = models.ForeignKey(
        "User",
        on_delete=models.CASCADE,
        related_name="live_chat_sessions_as_seller",
        db_column="seller_user_id",
        limit_choices_to={"role_id": UserRole.ROLE_SELLER},
    )
    customer = models.OneToOneField(
        "Customer",
        on_delete=models.SET_NULL,
        related_name="live_chat_session",
        db_column="customer_id",
        null=True,
        blank=True,
    )
    # Visitor fields for chat sessions that should NOT create Customer rows.
    visitor_name = models.CharField(max_length=150, blank=True, default="")
    visitor_mobile_number = models.CharField(max_length=30, blank=True, default="")
    visitor_email = models.EmailField(blank=True, default="")
    visitor_payload = models.JSONField(default=dict, blank=True)
    source_bot = models.ForeignKey(
        "Bot",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="live_chat_sessions",
        db_column="source_bot_id",
    )
    assigned_team_manager = models.ForeignKey(
        "User",
        on_delete=models.SET_NULL,
        related_name="assigned_live_chat_sessions_as_manager",
        db_column="assigned_team_manager_id",
        null=True,
        blank=True,
        limit_choices_to={"role_id": UserRole.ROLE_TEAM_MANAGER},
    )
    assigned_agent = models.ForeignKey(
        "User",
        on_delete=models.SET_NULL,
        related_name="assigned_live_chat_sessions_as_agent",
        db_column="assigned_agent_id",
        null=True,
        blank=True,
        limit_choices_to={"role_id": UserRole.ROLE_AGENT},
    )
    # Shared across seller + assigned team roles (see live-chat/support/sessions/ PATCH).
    lead_pipeline_status = models.CharField(max_length=40, blank=True, default="")
    # True = created from Lead Pipeline "Add Lead"; hidden from default live-chat inbox list.
    is_manual_pipeline_lead = models.BooleanField(default=False, db_index=True)

    # Token used by the bot widget (customer-facing iframe) to send/receive messages.
    public_token = models.CharField(
        max_length=64,
        unique=True,
        db_index=True,
        # Must be callable so every new session gets a unique token.
        default=uuid.uuid4,
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "live_chat_session"
        indexes = [
            models.Index(fields=["seller_user", "created_at"]),
            models.Index(fields=["customer", "created_at"]),
            models.Index(fields=["assigned_team_manager", "created_at"]),
            models.Index(fields=["assigned_agent", "created_at"]),
        ]

    def __str__(self) -> str:
        ref = self.customer_id if self.customer_id else (self.visitor_name or "anonymous")
        return f"LiveChatSession #{self.session_id} ({ref})"


