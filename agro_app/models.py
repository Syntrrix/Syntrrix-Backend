class OnlineOrder(models.Model):
    """
    Online catalogue order: created at widget checkout with status=pending (MySQL row);
    seller approve sets status=approved and creates OnlineOrderItem rows; reject sets rejected.
    """

    STATUS_PENDING = "pending"
    STATUS_APPROVED = "approved"
    STATUS_REJECTED = "rejected"
    STATUS_CHOICES = [
        (STATUS_PENDING, "Pending"),
        (STATUS_APPROVED, "Approved"),
        (STATUS_REJECTED, "Rejected"),
    ]

    order_id = models.AutoField(primary_key=True)
    seller_user = models.ForeignKey(
        User,
        on_delete=models.CASCADE,
        related_name="online_orders",
        db_column="seller_user_id",
        limit_choices_to={"role_id": UserRole.ROLE_SELLER},
    )
    source_bot = models.ForeignKey(
        Bot,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="online_orders",
        db_column="source_bot_id",
    )

    data_hub_table_id = models.CharField(max_length=64, blank=True, default="")
    data_hub_row_id = models.CharField(max_length=64, blank=True, default="")

    customer_name = models.CharField(max_length=150, blank=True, default="")
    customer_phone = models.CharField(max_length=30, blank=True, default="")
    customer_email = models.EmailField(blank=True, default="")
    customer_address = models.TextField(blank=True, default="")

    total_amount = models.DecimalField(max_digits=12, decimal_places=2, default=0)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default=STATUS_PENDING)
    # Dedicated MySQL column `order_no` (not `created_at`) — placed after `status` via migration 0033 on MySQL.
    order_no = models.CharField(
        "order no",
        max_length=40,
        null=True,
        blank=True,
        unique=True,
        db_index=True,
        db_column="order_no",
        help_text="Public reference from checkout; copied from Data Hub row when seller approves.",
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "online_order"
        indexes = [
            models.Index(fields=["seller_user", "created_at"]),
            models.Index(fields=["status", "created_at"]),
            models.Index(fields=["data_hub_table_id", "data_hub_row_id"]),
        ]

    def __str__(self) -> str:
        ref = (self.order_no or "").strip()
        if ref:
            return f"OnlineOrder {ref} (#{self.order_id}, {self.status})"
        return f"OnlineOrder #{self.order_id} ({self.status})"


