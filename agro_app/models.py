def generate_public_order_no() -> str:
    """Customer-facing order reference; format matches bot widget checkout (date + random hex)."""
    from django.utils import timezone

    d = timezone.now().strftime("%Y%m%d")
    return f"ORD-{d}-{secrets.token_hex(4).upper()}"


