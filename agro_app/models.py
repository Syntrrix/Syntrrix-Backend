class Batch(models.Model):
    """
    Batch model that stores batch information linked to a product and supplier.
    Used for tracking inventory batch-wise with expiry dates.
    """

    batch_id = models.AutoField(primary_key=True)
    batch_name = models.CharField(max_length=100)
    product = models.ForeignKey(
        Product,
        on_delete=models.CASCADE,
        related_name="batches",
        db_column="product_id",
    )
    supplier = models.ForeignKey(
        'Supplier',
        on_delete=models.CASCADE,
        related_name="batches",
        db_column="supplier_id",
    )
    expiry_date = models.DateField(null=True, blank=True)
    manufacturing_date = models.DateField(null=True, blank=True)
    purchase_price = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    selling_price = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    mrp = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    initial_quantity = models.PositiveIntegerField(default=0)
    available_quantity = models.PositiveIntegerField(default=0)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "batch"
        indexes = [
            models.Index(fields=["product", "expiry_date"]),
            models.Index(fields=["supplier", "created_at"]),
            models.Index(fields=["product", "supplier"]),
        ]
        ordering = ["expiry_date"]  # Default ordering by expiry date (nearest first)

    def __str__(self) -> str:
        return f"{self.batch_name} (Product: {self.product.product_name}, Supplier: {self.supplier.supplier_name})"

    @property
    def is_expired(self):
        """Check if the batch is expired."""
        from django.utils import timezone
        if self.expiry_date:
            return self.expiry_date < timezone.now().date()
        return False

    @property
    def days_until_expiry(self):
        """Get number of days until expiry. Returns None if no expiry date."""
        from django.utils import timezone
        if self.expiry_date:
            delta = self.expiry_date - timezone.now().date()
            return delta.days
        return None


