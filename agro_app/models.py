class InventoryTransaction(models.Model):
    """
    Tracks all stock in and stock out events for inventory management.
    """
    TRANSACTION_TYPE_IN = "in"
    TRANSACTION_TYPE_OUT = "out"
    TRANSACTION_TYPE_CHOICES = [
        (TRANSACTION_TYPE_IN, "Stock In"),
        (TRANSACTION_TYPE_OUT, "Stock Out"),
    ]

    transaction_id = models.AutoField(primary_key=True)
    product = models.ForeignKey(Product, on_delete=models.CASCADE)
    batch = models.ForeignKey(
        'Batch',
        on_delete=models.SET_NULL,
        related_name="inventory_transactions",
        db_column="batch_id",
        null=True,
        blank=True,
    )
    batch_name = models.CharField(max_length=100, blank=True)  # Keep for backward compatibility
    quantity = models.PositiveIntegerField()
    transaction_type = models.CharField(max_length=3, choices=TRANSACTION_TYPE_CHOICES)
    reason = models.CharField(max_length=100, blank=True)  # e.g., "Purchase", "Damaged", "Manual Adjustment"
    reference_id = models.CharField(max_length=100, blank=True)  # e.g., purchase ID, sale ID
    date = models.DateField()
    expiry_date = models.DateField(null=True, blank=True)  # Expiry date for stock-in
